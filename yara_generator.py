import sys
import os
import string
import argparse

def extract_strings(file_path, min_length=4):
    """Extracts printable ASCII strings from a file."""
    try:
        with open(file_path, 'rb') as f:
            content = f.read()
    except IOError as e:
        print(f"Error reading file: {e}", file=sys.stderr)
        sys.exit(1)
    
    current_string = ""
    extracted_strings = set()
    
    for byte in content:
        char = chr(byte)
        if char in string.printable and 32 <= byte <= 126:
            current_string += char
        else:
            if len(current_string) >= min_length:
                extracted_strings.add(current_string)
            current_string = ""
            
    if len(current_string) >= min_length:
        extracted_strings.add(current_string)
        
    return list(extracted_strings)

def format_yara_rule(file_path):
    """Formats the YARA rule as a string."""
    base_name = os.path.basename(file_path)
    # Clean the name for valid YARA rule syntax (alphanumeric and underscores)
    rule_name = "".join(c if c.isalnum() else "_" for c in base_name)
    if not rule_name or rule_name[0].isdigit():
        rule_name = "_" + rule_name

    strings = extract_strings(file_path)
    
    lines = [
        f"rule AutoGenerated_{rule_name}",
        "{",
        "    meta:",
        f'        description = "Automatically generated rule from {base_name}"',
        "    strings:"
    ]
    
    # Limit to the first 20 strings to prevent oversized rules
    for i, s in enumerate(strings[:20]):
        escaped_string = s.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'        $string_{i} = "{escaped_string}"')
        
    lines.extend([
        "    condition:",
        "        any of them",
        "}"
    ])
    
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(description="Generate a basic YARA rule from a file's strings.")
    parser.add_argument("target_file", help="The file to analyze and extract strings from.")
    parser.add_argument("-o", "--output", help="Optional path to save the generated YARA rule file.")
    
    args = parser.parse_args()
    
    if not os.path.exists(args.target_file):
        print(f"Error: File '{args.target_file}' does not exist.", file=sys.stderr)
        sys.exit(1)
        
    rule_text = format_yara_rule(args.target_file)
    
    if args.output:
        try:
            with open(args.output, 'w', encoding='utf-8') as f:
                f.write(rule_text + "\n")
            print(f"Successfully saved YARA rule to {args.output}")
        except IOError as e:
            print(f"Error writing to output file: {e}", file=sys.stderr)
            sys.exit(1)
    else:
        print(rule_text)

if __name__ == "__main__":
    main()
